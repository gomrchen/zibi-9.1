                    if (e.length < 2 || ~~e || that.loading) {
                        return;
                    }
                    var ajax_data = {
                        per_page: 20,
                        search: e,
                        type: 'post',
                        post_type: ['shop_product'],
                        order_by: 'post_title',
                    };
                    setAttributes({
                        loading: true,
                    });
